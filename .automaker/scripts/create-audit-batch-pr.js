/**
 * create-audit-batch-pr.js — PR Creation for Audit Batches
 *
 * Creates a single PR from a completed batch branch to dev. Includes proper
 * GitHub labels, description template with audit summary and component list,
 * and enables auto-merge on CI success.
 *
 * Usage:
 *   node .automaker/scripts/create-audit-batch-pr.js --date 20260326
 *   node .automaker/scripts/create-audit-batch-pr.js --metadata path/to/metadata.json
 *
 * Prerequisites:
 *   - gh CLI authenticated
 *   - Batch branch pushed to origin
 *   - Batch finalized (scripts/finalize-audit-batch.sh)
 */

import { readFileSync, existsSync } from 'fs';
import { join, basename } from 'path';
import { execSync } from 'child_process';

const REPO_ROOT = process.cwd();
const REPO = 'bookedsolidtech/helix';

/**
 * Load batch metadata
 */
function loadMetadata(metadataPath) {
  if (!existsSync(metadataPath)) {
    console.error('[ERROR] Metadata not found:', metadataPath);
    process.exit(1);
  }
  return JSON.parse(readFileSync(metadataPath, 'utf-8'));
}

/**
 * Load PR description template
 */
function loadTemplate() {
  const templatePath = join(
    REPO_ROOT,
    '.automaker/templates/audit-batch-pr-description.md'
  );
  if (!existsSync(templatePath)) {
    return null;
  }
  return readFileSync(templatePath, 'utf-8');
}

/**
 * Generate PR description from metadata
 */
function generateDescription(metadata) {
  const { components, timing, batchId, changeset } = metadata;
  const completed = components.completed || [];
  const failed = components.failed || [];
  const skipped = components.skipped || [];
  const total = components.total || 0;

  const componentList = completed
    .map((c) => {
      const t = timing.perComponent[c];
      const duration = t && t.durationMinutes ? ` (${t.durationMinutes}min)` : '';
      return `- [x] \`${c}\`${duration}`;
    })
    .join('\n');

  const failedList = failed.map((c) => `- [ ] \`${c}\` (failed)`).join('\n');
  const skippedList = skipped.map((c) => `- [ ] \`${c}\` (skipped)`).join('\n');

  const totalDuration = timing.totalDurationMinutes
    ? `${timing.totalDurationMinutes} minutes`
    : 'unknown';

  const body = `## Audit Batch Summary

**Batch ID:** ${batchId}
**Components:** ${completed.length}/${total} completed
**Duration:** ${totalDuration}
**Changeset:** ${changeset.bumpType} bump for ${changeset.scope}

## Components Audited

${componentList}
${failedList ? '\n### Failed\n' + failedList : ''}
${skippedList ? '\n### Skipped\n' + skippedList : ''}

## CI Optimization

This PR consolidates ${total} component audits into a single CI run:
- **Before:** ${total} PRs x 15 jobs = ${total * 15} CI jobs
- **After:** 1 PR x 15 jobs = 15 CI jobs
- **Reduction:** ${Math.round(((total * 15 - 15) / (total * 15)) * 100)}%

## Review Notes

Each component audit is an atomic commit on this branch. Review commits
individually for per-component changes, or review the full diff for the
consolidated view.

---
*Generated by audit-batch-orchestrator*`;

  return body;
}

/**
 * Create PR using gh CLI
 */
function createPR(metadata, description) {
  const { branch } = metadata;
  const completed = metadata.components.completed || [];
  const total = metadata.components.total || 0;
  const date = metadata.batchId.replace('batch-', '');

  const title = `audit: deep quality batch ${date} (${completed.length} components)`;
  const labels = ['audit-batch', 'deep-quality', 'infra'];

  console.log(`[INFO] Creating PR: ${title}`);
  console.log(`[INFO] Branch: ${branch} → dev`);

  try {
    // Create PR
    const prUrl = execSync(
      `gh pr create --repo ${REPO} --base dev --head "${branch}" --title "${title}" --body "${description.replace(/"/g, '\\"')}" ${labels.map((l) => `--label "${l}"`).join(' ')}`,
      { encoding: 'utf-8', maxBuffer: 1024 * 1024 }
    ).trim();

    console.log(`[OK] PR created: ${prUrl}`);

    // Extract PR number
    const prNumber = prUrl.match(/\/(\d+)$/)?.[1];

    if (prNumber) {
      // Enable auto-merge
      try {
        execSync(
          `gh pr merge ${prNumber} --auto --merge --repo ${REPO}`,
          { encoding: 'utf-8' }
        );
        console.log(`[OK] Auto-merge enabled for PR #${prNumber}`);
      } catch (e) {
        console.warn(`[WARN] Could not enable auto-merge: ${e.message}`);
      }

      // Add skip-changeset label if changeset is already included
      if (metadata.changeset.consolidated) {
        console.log('[INFO] Changeset is consolidated in the branch — no skip needed');
      }
    }

    return { url: prUrl, number: prNumber };
  } catch (e) {
    console.error(`[ERROR] Failed to create PR: ${e.message}`);
    return null;
  }
}

// ── CLI Entry Point ─────────────────────────────────────────────────────────

const args = process.argv.slice(2);

if (args.includes('--help')) {
  console.log(
    'Usage: node create-audit-batch-pr.js [--date YYYYMMDD] [--metadata PATH] [--dry-run]'
  );
  process.exit(0);
}

const dateIndex = args.indexOf('--date');
const metadataIndex = args.indexOf('--metadata');
const dryRun = args.includes('--dry-run');

let metadataPath;

if (metadataIndex >= 0 && args[metadataIndex + 1]) {
  metadataPath = args[metadataIndex + 1];
} else {
  const date =
    dateIndex >= 0 && args[dateIndex + 1]
      ? args[dateIndex + 1]
      : new Date().toISOString().replace(/-/g, '').slice(0, 8);
  metadataPath = join(
    REPO_ROOT,
    `.automaker/audits/batch-${date}-metadata.json`
  );
}

const metadata = loadMetadata(metadataPath);
const description = generateDescription(metadata);

if (dryRun) {
  console.log('[DRY RUN] Would create PR with:');
  console.log('');
  console.log('Title:', `audit: deep quality batch ${metadata.batchId.replace('batch-', '')} (${metadata.components.completed.length} components)`);
  console.log('');
  console.log('Body:');
  console.log(description);
  process.exit(0);
}

const result = createPR(metadata, description);

if (result) {
  console.log('');
  console.log(`PR URL: ${result.url}`);
  console.log(`PR #: ${result.number}`);
}

export { generateDescription, loadMetadata };
